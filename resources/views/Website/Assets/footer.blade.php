function showintekform(){
    var client_id_fk = $("#client_id_fk").val();
   
    $.ajax({
        type: "POST",
        url: "{{url('api/clientintakForm')}}",
        data: {'client_id_fk':client_id_fk},
        dataType: "json",

        success: function (data){
            $("#clientintakeform").empty();
            $("#clientintakeform").append(data.data);
            $('#clienldetailstintakeform').modal('show');
        },
        error: function (error) {
            console.log(error);
            alert("Data loading issue");
        }
    });

} 

